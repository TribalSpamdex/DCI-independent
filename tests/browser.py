import json, os, signal, socket, time
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    browser=getattr(p,os.getenv('DCI_BROWSER','chromium')).launch()
    ctx=browser.new_context(viewport={"width":390,"height":844}, is_mobile=True, has_touch=True)
    page=ctx.new_page()
    errors=[]
    page.on("pageerror",lambda e: errors.append(str(e)))
    page.goto("http://127.0.0.1:8765/index.html")
    page.locator("#version").wait_for()
    page.locator("#fact input[name=key]").fill("grip")
    page.locator("#fact input[name=value]").fill("middle")
    page.locator("#fact button").click()
    assert page.locator("#facts").inner_text().find("middle")>=0
    page.reload()
    assert page.locator("#facts").inner_text().find("middle")>=0
    page.locator("#demo").click()
    assert "SIMULATION ONLY" in page.locator("#report").inner_text()
    assert "temporary-focus" in page.locator("#report").inner_text()
    assert "50%" in page.locator("#report").inner_text()
    assert "20%" in page.locator("#report").inner_text()
    assert page.locator("#propose").is_disabled()
    page.locator("#scenario").select_option("equipment")
    page.locator("#demo").click()
    assert "Decision: investigate" in page.locator("#report").inner_text()
    page.locator("#scenario").select_option("pain")
    page.locator("#demo").click()
    assert "Decision: stop" in page.locator("#report").inner_text()
    page.locator("#scenario").select_option("decline")
    page.locator("#demo").click()
    page.locator(".question").filter(has_text="Did equipment change").get_by_role("button",name="yes",exact=True).click()
    assert "Decision: investigate" in page.locator("#report").inner_text()
    data=page.evaluate("JSON.parse(localStorage.getItem('DCI-independent:foundation:v1'))")
    assert len(data["observations"])==0
    assert len(data.get("answers",[]))==0
    assert len(data["interventions"])==0
    page.locator("#checkout button").click()
    assert "legal scoring routes" in page.locator("#routes").inner_text()
    page.locator("#throw input[name=protocol]").fill("test-dart")
    page.locator("#throw select[name=aim]").select_option("D20")
    page.locator("#throw select[name=actual]").select_option("S1")
    page.locator("#throw button").click()
    page.locator("#target-report").click()
    assert "1 recorded darts" in page.locator("#targets").inner_text()
    page.reload()
    page.locator("#target-report").click()
    assert "1 recorded darts" in page.locator("#targets").inner_text()
    page.locator("#analyse").click()
    assert "balanced" in page.locator("#report").inner_text()
    page.locator("#propose").click()
    assert "No supported focus" in page.locator("#status").inner_text()
    page.locator("#readiness select[name=fatigue]").select_option("high")
    page.locator("#readiness button").click()
    page.locator("#analyse").click()
    assert "reduce-load" in page.locator("#report").inner_text()
    page.locator("#readiness select[name=fatigue]").select_option("normal")
    page.locator("#readiness button").click()
    page.locator("#difficulty select[name=skill]").select_option("doubles")
    page.locator("#difficulty input[name=attempts]").fill("10")
    page.locator("#difficulty input[name=successes]").fill("8")
    page.locator("#difficulty button").click()
    page.locator("#equipment input[value=weight]").check()
    page.locator("#equipment input[name=measuredDecline]").check()
    page.locator("#equipment button").click()
    assert "counterbalanced" in page.locator("#equipment-report").inner_text()
    page.reload()
    assert "1 recorded entries" in page.locator("#readiness-history").inner_text()
    assert "1 recorded entries" in page.locator("#difficulty-history").inner_text()
    page.locator("#goal select[name=skill]").select_option("doubles")
    page.locator("#goal input[name=protocol]").fill("fixed")
    page.locator("#goal input[name=target]").fill("40")
    page.locator("#goal button").click()
    assert "Target 40%" in page.locator("#goals").inner_text()
    page.locator("#trial select[name=skill]").select_option("doubles")
    page.locator("#trial input[name=protocol]").fill("fixed")
    page.locator("#trial input[name=baseline]").fill("normal cue")
    page.locator("#trial input[name=alternative]").fill("external cue")
    page.locator("#trial button").click()
    assert "active" in page.locator("#trials").inner_text()
    page.locator("#make-plan").click()
    page.locator("#session-plan input").first.fill("10")
    page.locator("#session-plan button").click()
    assert "1 logged sessions" in page.locator("#session-history").inner_text()
    page.locator("#tactics input[name=score]").fill("40")
    page.locator("#tactics select[name=actual1]").select_option("S20")
    page.locator("#tactics button").click()
    assert "Remaining 20" in page.locator("#tactical-result").inner_text()
    assert "D10" in page.locator("#tactical-result").inner_text()
    page.reload()
    assert "Target 40%" in page.locator("#goals").inner_text()
    assert "1 logged sessions" in page.locator("#session-history").inner_text()
    assert "active" in page.locator("#trials").inner_text()
    page.evaluate("navigator.serviceWorker.ready")
    page.wait_for_function("navigator.serviceWorker.controller !== null")
    if os.getenv("DCI_BROWSER")=="webkit":
        # Playwright issue #42775: set_offline can reject service-worker responses
        # even when the worker returns literal HTML. Stop the actual local origin.
        assert page.evaluate("caches.open('DCI-independent:foundation:0.2.0').then(c=>c.match('./index.html')).then(Boolean)")
        pid=int(os.environ["DCI_SERVER_PID"])
        os.kill(pid,signal.SIGTERM)
        for _ in range(50):
            with socket.socket() as sock:
                sock.settimeout(.2)
                if sock.connect_ex(("127.0.0.1",8765))!=0:
                    break
            time.sleep(.1)
        else:
            raise AssertionError("Local origin did not stop")
        page.goto("http://127.0.0.1:8765/index.html?v=0.2.0&offline-test=1")
    else:
        ctx.set_offline(True)
        page.reload()
    page.locator("#analyse").click()
    assert "balanced" in page.locator("#report").inner_text()
    page.locator("#demo").click()
    assert "SIMULATION ONLY" in page.locator("#report").inner_text()
    assert not errors,errors
    browser.close()
print("Mobile viewport persistence, isolation, checkout and offline smoke test passed")
